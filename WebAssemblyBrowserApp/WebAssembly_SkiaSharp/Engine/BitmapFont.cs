    /// <summary>字体基准：把 CSS 字号换算成点阵像素边长（7 行 ≈ 8 个字号单位）。</summary>
    public static float PixelSize(float fontSize) => MathF.Max(1f, MathF.Round(fontSize / 8f));

    /// <summary>测量文本宽度（逻辑像素）。</summary>
    public static float Measure(string? text, float fontSize)
    {
        if (string.IsNullOrEmpty(text)) return 0f;
        float s = PixelSize(fontSize);
        return text.Length * Advance * s - s;
    }

    /// <summary>文本高度（逻辑像素）。</summary>
    public static float LineHeight(float fontSize) => PixelSize(fontSize) * GlyphHeight;

    /// <summary>
    /// 绘制文本。x/y 语义与 Canvas2D 一致：y 为文本垂直中心，align 为 left/center/right。
    /// </summary>
    public static void Draw(SKCanvas canvas, SKPaint paint, string? text, float x, float y,
        float fontSize, string align, bool bold)
    {
        if (string.IsNullOrEmpty(text)) return;

        float s = PixelSize(fontSize);
        float w = Measure(text, fontSize);
        float left = align switch
        {
            "center" => x - w / 2,
            "right" => x - w,
            _ => x,
        };
        float top = y - GlyphHeight * s / 2f;

        string upper = text.ToUpperInvariant();
        float cursor = left;
        foreach (char ch in upper)
        {
            if (!Glyphs.TryGetValue(ch, out var rows))
            {
                cursor += Advance * s;   // 缺字：留空
                continue;
            }

            for (int r = 0; r < GlyphHeight; r++)
            {
                var row = rows[r];
                int c = 0;
                while (c < GlyphWidth)
                {
                    if (row[c] == '0') { c++; continue; }
                    int start = c;
                    while (c < GlyphWidth && row[c] == '1') c++;
                    float rx = cursor + start * s;
                    float ry = top + r * s;
                    canvas.DrawRect(rx, ry, (c - start) * s, s, paint);
                    if (bold) canvas.DrawRect(rx + s * 0.5f, ry, (c - start) * s, s, paint);
                }
            }
            cursor += Advance * s;
        }
    }
