    private static Type[] localizationEnumTypes =
    [
        typeof(MirClass),
        typeof(RequiredClass),
        typeof(Stat),
        typeof(BuffType),
        typeof(PoisonType),
        typeof(AwakeType),
        typeof(MonsterType),
        typeof(HeroBehaviour)
    ];

    static GameLanguage()
    {
        PopulateEnumToClientTextMap(localizationEnumTypes);
    }

    private static void PopulateEnumToClientTextMap(Type[] localizationEnumTypes)
    {
        foreach (var enumType in localizationEnumTypes)
        {
            if (!enumType.IsEnum) continue;
            foreach (var enumName in Enum.GetNames(enumType))
            {
                ClientTextMap.Enum.TryAdd($"{enumType.Name}_{enumName}", enumName);
            }
        }
    }

    // 把 src 中已有的 key 合并进 dst（已存在的 key 才覆盖，不会新增 key）
    private static void MergeInto(TextMap dst, TextMap src)
    {
        foreach (var item in dst.Text)
        {
            if (src.Text.TryGetValue(item.Key, out var value))
            {
                dst.Text[item.Key] = value;
            }
        }

        foreach (var item in dst.Enum)
        {
            if (src.Enum.TryGetValue(item.Key, out var value))
            {
                dst.Enum[item.Key] = value;
            }
        }
    }
    
    public static async Task LoadLanguageAsync(string languageJsonPath)
    {
        byte[] data = await BrowserResource.GetBytesAsync(RemoteWebSetting.LanguageBaseRootDir + languageJsonPath).ConfigureAwait(false);
        string json = Encoding.UTF8.GetString(data);
        var language = JsonTool.FromJson<TextMap>(json, AppJsonContext.Default.TextMap);
        if (language != null)
        {
            MergeInto(ClientTextMap, language);
        }
    }

    public static string GetLocalization(this TextMap map, ClientTextKeys key)
    {
        if (map.Text.TryGetValue(key.ToString(), out var value))
        {
            return value;
        }

        return key.ToString();
    }

